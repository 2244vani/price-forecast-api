
import streamlit as st
import requests
import pandas as pd
import plotly.express as px

# Page configuration
st.set_page_config(
    page_title="Monthly Price Forecast",
    page_icon="📈",
    layout="wide"
)

# Dashboard title
st.title("📈 Monthly Price Forecast Dashboard")
st.write("Explore monthly price predictions generated by our forecasting API.")

# API URL
API_URL = "http://127.0.0.1:8000"

# User selects forecast period
months = st.slider(
    "Select number of months to forecast",
    min_value=1,
    max_value=24,
    value=3
)

# Get predictions from FastAPI
if st.button("Generate Forecast"):
    try:
        response = requests.get(
            f"{API_URL}/forecast",
            params={"months": months},
            timeout=10
        )

        response.raise_for_status()
        result = response.json()

        forecast_data = pd.DataFrame(result["forecast"])

        st.success("Forecast generated successfully!")

        st.metric(
            "Latest date in training data",
            result["latest_data_date"]
        )

        st.subheader("Forecast Results")
        st.dataframe(forecast_data, use_container_width=True)

        st.subheader("Predicted Price Trend")

        figure = px.line(
            forecast_data,
            x="date",
            y="predicted_price",
            markers=True,
            title="Monthly Price Forecast"
        )

        figure.update_layout(
            xaxis_title="Month",
            yaxis_title="Predicted Price"
        )

        st.plotly_chart(figure, use_container_width=True)

        st.caption(
            "Note: Predictions are based on the available training data. "
            "The dataset currently ends in September 2025, so these are "
            "projections from that date, not current market prices."
        )

    except requests.exceptions.RequestException:
        st.error(
            "Cannot connect to the forecasting API. "
            "Make sure your FastAPI server is running."
        )

    except (KeyError, ValueError):
        st.error("The API returned data in an unexpected format.")
